const themeCreator = (config, options) => {
  Object.keys(config).forEach((merchant) => {
    config[merchant] = {
      ...COMMON_COLORS,
      ...config[merchant],
    };
  });
  const createTheme = createThemes(config, options);
  return {
    ...createTheme,
    config: {
      ...createTheme.config,
      theme: {
        ...createTheme.config.theme,
        extend: {
          ...createTheme.config.theme.extend,
          hexColors: {
            ...createTheme.config.theme.extend.colors,
            ...COMMON_COLORS,
            ...config[options.defaultTheme],
          },
        },
      },
    },
  };
};

